/**
 * royale/fx.js — particles, tracers, damage numbers, camera shake.
 *
 * ONE InstancedMesh pool of camera-facing soft quads (single draw call, 1,024 slots)
 * drives every burst: muzzle flash, impacts, explosions, harvest chips, storm sparkles,
 * dust. Tracers are the same pool: a thin quad stretched along the round's flight
 * direction and billboarded around that axis. Damage numbers are DOM elements
 * projected from world space (crisp text, no canvas blur — the shroud-font lesson).
 *
 * WAVE 4 (plan P1.4): the pool used to be 1,024 flat unlit CUBES — a hit drew a
 * coloured box and a tracer a flat yellow stick, which broke the "no primitives as
 * final art" rule. Now: a 2x2 texture atlas (spark star / soft puff / round glow /
 * tracer streak) from assets/fx/*.png (contract C-ART-FX, Kenney Light Masks, CC0), with
 * a procedural canvas fallback for any missing file so there are STILL no cubes; a
 * premultiplied-alpha ShaderMaterial where each instance carries an "additive"
 * fraction (alpha 0 = pure additive, 1 = normal blend), so sparks glow and smoke
 * still darkens in the same single draw. renderOrder 7: above the storm wall (5) and
 * the loot beams / rings (>= 6, contract C-LOOT-RENDER).
 *
 * PARITY P1-E (LC-40): an explosion was 26 sparks + 14 grey dots + one additive sprite and a
 * flat ring, gone in about 3 frames at 14 m (40 px of glow on frame 1, nothing by frame 8).
 * The pool now also samples a second sheet, assets/fx/fx_sheet.png (4 x 4 cells of 128 px,
 * colour + alpha, original procedural art generated by the P1-E tool, CC0): an 8-frame
 * fireball flipbook, 4 lit smoke puffs, a debris chunk, a dust ring, a wood splinter and a
 * droplet spatter (procedural canvas fallback while it loads or if it is missing). Pool code
 * 4 + s picks sheet cell s; code + 32 lays the quad FLAT along the instance matrix's first two
 * columns (ground rings) instead of facing the camera. An explosion is now a flash, a flipbook
 * fireball, a flat dust ring, sparks, tumbling debris, a ground dust skirt and a 3.0-4.4 s smoke
 * column that climbs past 6 m - every piece in the ONE pool draw, so the old per-blast Sprite +
 * RingGeometry meshes (2 extra draws per live blast) are gone, and a scorch mark goes into
 * reserved slots of the always-drawn bullet-decal mesh (+0 draws). Bullet impacts read per
 * surface: flesh (mist + spatter), stone (dust + chips + a hot fleck), wood (pale dust +
 * splinters), dirt (a spurt + clods), metal (spark streaks + a pin flash) and water (a splash
 * where a round meets the sea). Persistent marks (bullet holes, scorches) live in the scene
 * group "decals", not "fx": "fx" is the transient layer.
 *
 * PARITY P2+P3 (lane fx):
 *  - C-SMOKE: smoke-grenade clouds from W.smokes [{x,y,z,r,t0,t1}] (weapons.js owns the list; maps.js blocks sight through
 *    the same spheres). They are NOT pool quads: a cloud lives ~20-30 s and the 1,024-slot ring would recycle it in a busy
 *    fight. One more InstancedMesh, "fx-smoke", in its own scene group "smoke": lit soft puffs (sun + hemisphere read from
 *    the live scene lights, a per-pixel sphere normal, per-puff cloud occlusion), faded where they meet the ground (soft
 *    intersection without a depth texture) and near the camera, sorted far-to-near, plus a veil when the camera is inside a
 *    cloud (placed just beyond your character, so you still see yourself). Positions are a pure function of the smoke entry
 *    and W.t (no per-puff state). No smoke = count 0 = no draw call.
 *  - C-DBNO: collapse dust + mist on 'actorDowned', blood drips while crawling, a pulsing ground ring under a downed
 *    TEAMMATE, a contracting light ring + rising motes during a revive channel, a burst on 'actorRevived'.
 *  - C-FALL: 'fallDamage' kicks a ground ring, a dust skirt and clods scaled by the damage.
 *  - LC-16 guns: dmr / lmg / burst muzzle and tracer variants (class fallback for any id the sim adds).
 *  - P1-E check items: the young fireball frames (first 0.05-0.15 s) re-made in fx_sheet.png (they read as pale cream blobs);
 *    the scorch decal is charred grey-brown, not near-black (a second blast on a scorch measured 7.9-13.9x glare).
 *  - C-GFX: per-tier FX quality (fxQ below): low trims quad counts, medium / high keep the P1-E look, ultra adds puffs and
 *    impact distance. Touch devices always get the medium set (phone paths unchanged).
 */
