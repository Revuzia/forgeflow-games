// Explosion flash. A 95-damage launcher round with a 3.5 m splash resolved as 40
// cubes and a low-passed thump. A real PointLight would force a shader recompile
// across every material in the scene on the first blast (a visible hitch on a
// browser GPU) — at the match bloom of 0.14 an additive glow reads as a flash
// for free. (P1-E: the flash is now a pool quad, ST_BFLASH, not its own Sprite.)
// Bullet decals: one InstancedMesh of camera-independent quads oriented to the
// impact normal, ring-buffered. Instances park at scale 0 until used; a fresh
// match clears the scene groups, so re-adoption also re-parks every slot (old
// map's holes must not reappear floating in the new map).
// P1-E: SCORCH_N extra slots at the end of the same mesh take explosion scorch marks
// (their own little ring, so a spray into a wall never wipes the last blast's scorch),
// and the mesh lives in the scene group "decals": persistent marks, not transient fx.
const DECAL_N = 64, SCORCH_N = 8, DECAL_ALL = DECAL_N + SCORCH_N, DECAL_EDGE = 0.14;
let decalMesh = null, decalCursor = 0, scorchCursor = 0, scorchCount = 0;
const _dM = new THREE.Matrix4(), _dQ = new THREE.Quaternion(), _dQ2 = new THREE.Quaternion();
const _dN = new THREE.Vector3(), _dP = new THREE.Vector3(), _dS = new THREE.Vector3();
const _dZ = new THREE.Vector3(0, 0, 1);
function parkDecals() {
  _dM.makeScale(0, 0, 0);
  for (let i = 0; i < DECAL_ALL; i++) decalMesh.setMatrixAt(i, _dM);
  decalMesh.instanceMatrix.needsUpdate = true;
  decalCursor = 0; scorchCursor = 0;
}
/** The decal mask: a dark soft disc whose rim is broken up by fixed-seed noise (a bullet hole at 14 cm, a scorch at 6 m). */
function makeDecalTexture() {
  const S = 128, cv = document.createElement("canvas"); cv.width = cv.height = S;
  const c2 = cv.getContext("2d");
  const id = c2.createImageData(S, S), d = id.data;
  let sd = 0x5c0c4;
  const rnd = () => { sd = (sd * 1664525 + 1013904223) >>> 0; return sd / 4294967296; };
  const K = 24, rim = [];                                   // rim wobble, per angle (wraps)
  for (let i = 0; i < K; i++) rim.push(0.72 + 0.22 * rnd());
  const spots = [];                                         // a few darker soot clots
  for (let i = 0; i < 9; i++) { const a = rnd() * 6.2832, r = Math.sqrt(rnd()) * 0.55; spots.push([Math.cos(a) * r, Math.sin(a) * r, 0.08 + 0.12 * rnd()]); }
  for (let y = 0; y < S; y++) {
    for (let x = 0; x < S; x++) {
      const u = (x + 0.5) / S * 2 - 1, v = (y + 0.5) / S * 2 - 1;
      const r = Math.hypot(u, v);
      const t = (Math.atan2(v, u) / 6.2832 + 1) * K, i0 = Math.floor(t) % K, f = t - Math.floor(t);
      const R = rim[i0] + (rim[(i0 + 1) % K] - rim[i0]) * (f * f * (3 - 2 * f));
      let a = r < R ? 1 - smooth((r - 0.20 * R) / (0.80 * R)) * 0.55 : 0;          // dense core, softer outer half
      a *= 1 - smooth((r - R * 0.86) / (R * 0.14));
      let soot = 0;
      for (const sp of spots) { const dd = Math.hypot(u - sp[0], v - sp[1]); soot = Math.max(soot, 1 - smooth(dd / sp[2])); }
      a = Math.min(1, a * (0.86 + 0.14 * soot));
      const k = (y * S + x) * 4;
      // P23/fx: charred grey-brown (the scorch's own colour); bullet holes are darkened back to the old near-black by their
      // instance colour. Soot clots are a gentle step darker, never black: a second blast over a black clot measured 13.9x glare.
      d[k] = 25 - 4 * soot; d[k + 1] = 22 - 4 * soot; d[k + 2] = 19 - 3 * soot;
      d[k + 3] = Math.round(Math.max(0, Math.min(1, a * 0.9)) * 255);
    }
  }
  c2.putImageData(id, 0, 0);
  return new THREE.CanvasTexture(cv);
}
function ensureDecals(W) {
  if (decalMesh) {
    if (!decalMesh.parent) {
      parkDecals();
      W.group("decals").add(decalMesh);
    }
    return;
  }
  decalMesh = new THREE.InstancedMesh(
    new THREE.PlaneGeometry(DECAL_EDGE, DECAL_EDGE),
    new THREE.MeshBasicMaterial({
      map: makeDecalTexture(), transparent: true, depthWrite: false,
      polygonOffset: true, polygonOffsetFactor: -2, polygonOffsetUnits: -2,
    }),
    DECAL_ALL);
  decalMesh.name = "decals";
  decalMesh.frustumCulled = false;   // quads scattered map-wide: one sphere would span the map anyway
  // per-slot tint, made BEFORE the first compile (the instancing-colour program is linked by the warm-up, never mid-match):
  // the 64 bullet slots keep their old near-black, the 8 scorch slots show the mask's charred grey-brown
  const tint = new Float32Array(DECAL_ALL * 3);
  for (let i = 0; i < DECAL_ALL; i++) {
    const sc = i >= DECAL_N;
    tint[i * 3] = sc ? 1.0 : 0.78; tint[i * 3 + 1] = sc ? 0.97 : 0.72; tint[i * 3 + 2] = sc ? 0.94 : 0.64;
  }
  decalMesh.instanceColor = new THREE.InstancedBufferAttribute(tint, 3);
  parkDecals();
  W.group("decals").add(decalMesh);
}
/** A decal flush on a surface: slot, centre, unit normal, edge length in metres. */
function placeDecal(slot, x, y, z, nx, ny, nz, edge) {
  _dN.set(nx, ny, nz).normalize();
  _dQ.setFromUnitVectors(_dZ, _dN);
  _dQ2.setFromAxisAngle(_dZ, Math.random() * Math.PI * 2);
  _dQ.multiply(_dQ2);
  const ds = edge / DECAL_EDGE;
  _dS.set(ds, ds, ds);
  _dP.set(x, y, z);
  _dM.compose(_dP, _dQ, _dS);
  decalMesh.setMatrixAt(slot, _dM);
  decalMesh.instanceMatrix.needsUpdate = true;
}

// ── P1-E: per-surface bullet impacts and the explosion ──────────────────────
const _cd = new THREE.Vector3();
/** A random unit vector inside a cone round (nx, ny, nz); spread 0 = along it, 1 = roughly a hemisphere. Writes _cd. */
function coneDir(nx, ny, nz, spread) {
  let x, y, z, l;
  do { x = Math.random() * 2 - 1; y = Math.random() * 2 - 1; z = Math.random() * 2 - 1; l = x * x + y * y + z * z; } while (l > 1 || l < 1e-4);
  l = Math.sqrt(l);
  x = nx + spread * x / l; y = ny + spread * y / l; z = nz + spread * z / l;
  l = Math.hypot(x, y, z) || 1;
  return _cd.set(x / l, y / l, z / l);
}
function camDist(W, x, z) {
  const c = W.camera;
  return c ? Math.hypot(c.position.x - x, c.position.z - z) : 0;
}
