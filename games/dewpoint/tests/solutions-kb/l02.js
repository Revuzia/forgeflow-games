// Keyboard solution for l02 "Cold Shoulder". Headings (camYaw -90): +x = W, -x = S, -z = A, +z = D.
// Liquid does the walking and lining up (taps are precise, ice is not); ice is for the heavy plates, the glass and the crates.

const crate = (s, id) => s.level.crates.find((c) => c.id === id).body;

export function solve(k) {
  // 1. The Rink: hop both kerbs as a drop, freeze, slide over the heavy plate (the shutter lifts) and through the glass
  k.goTo(6.4, 0).hopTo('+x', { tap: 0.45 })
    .goTo(11.4, 0).hopTo('+x', { tap: 0.45 })
    .goTo(15.2, 0)
    .form('ice')
    .hold('+x', { until: (s, p) => p.x > 30 && s.level.panes[0].broken || p.x > 34, label: 'through the glass' })
    .expect((s) => s.level.panes[0].broken, 'first pane smashed')
    .stopNow()
    .form('liquid')
    // 2. The Crate Gallery: crate 1 south along the north rail, then east onto the heavy plate
    .goTo(41.8, -0.8)
    .goTo(44.5, -1.8)
    .goTo(44.5, -4.3)
    .goTo(46, -4.3, { tol: 0.42 })
    .form('ice')
    .hold('+z', { until: (s) => crate(s, 'crate1').z >= 1.6 })
    .stopNow()
    .form('liquid')
    .goTo(44.3, 0.4).goTo(44.3, crate(k.sim, 'crate1').z, { tol: 0.45 })
    .form('ice')
    .hold('+x', { until: (s) => crate(s, 'crate1').x >= 55.0, timeout: 14 })
    .stopNow()
    .expectSignal('hp1', true)
    .form('liquid')
    // 3. The Chute
    .goTo(61.5, 0, { order: 'zx' })
    .expect((s) => s.level.doors.find((d) => d.id === 'doorA').open >= 1, 'door A held open by the crate')
    .goTo(66, -0.8)
    .goTo(71, 0)
    .hold('+x', { until: (s, p) => p.y > 2.9 && p.x > 76, label: 'up the ramp to the deck' })
    .stopNow()
    .goTo(78.5, 0)
    .form('ice')
    .hold('+x', { until: (s) => s.level.panes.find((p) => p.id === 'pane2').broken, timeout: 8, label: 'second pane smashed' })
    .until((s, p) => p.form === 'liquid', { timeout: 4, label: 'melted on the hot tiles' })
    .stopNow()
    // 4. The Double Weight: crate 2 east along the south lane; ice through the glass at the stall mouth, then crate 3 east
    .goTo(102.5, -0.8)
    .goTo(103.4, -3.4)
    .form('ice')
    .hold('+x', { until: (s) => crate(s, 'crate2').x >= 113.9, timeout: 14, label: 'crate 2 onto plate A' })
    .stopNow()
    .expectSignal('hpA', true)
    .form('liquid')
    .goTo(101.4, 3.5, { tol: 0.6, order: 'xz' })
    .form('ice')
    .hold('+x', { until: (s) => crate(s, 'crate3').x >= 121.0, timeout: 16, label: 'crate 3 onto plate B' })
    .expect((s) => s.level.panes.find((p) => p.id === 'pane3').broken, 'third pane smashed')
    .stopNow()
    .expectSignal('hpB', true)
    .form('liquid')
    .goTo(126, 0, { order: 'zx' })
    .until((s) => s.level.doors.find((d) => d.id === 'doorW').open >= 1, { label: 'shutter up' })
    .goTo(131, -0.8)
    // 5. The Locked Kiln: film under the low wall, ice onto the heavy plate beyond, film back out, to the kiln door
    .expect((s) => !s.level.exits[0].open, 'exit starts locked')
    .goTo(150.2, 0)
    .form('film')
    .runTo('+x', 154.4)
    .form('ice')
    .hold('+x', { until: (s) => s.signals.get('exitOpen'), timeout: 6, label: 'heavy plate pressed' })
    .stopNow()
    .form('film')
    .runTo('-x', 150.2)
    .form('liquid')
    .expect((s) => s.level.exits[0].open, 'exit stays unlocked (latched)')
    .goTo(133.4, -3.6, { order: 'xz' })
    .expectExit({ timeout: 4 });
}
